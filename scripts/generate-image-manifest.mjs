import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { REPO_ROOT, GENERATED_IMAGES_ROOT, listOriginalPhotos, orientedDimensions, variantsForWidth } from "./image-settings.mjs";

export async function generateImageManifest() {
  const catalog = {};
  const photos = await listOriginalPhotos();
  for (const photo of photos) {
    const metadata = await sharp(photo.input).metadata();
    const { width, height } = orientedDimensions(metadata);
    const variants = [];
    for (const variant of variantsForWidth(width)) {
      const name = photo.index + "-" + variant.suffix + ".webp";
      const output = path.join(GENERATED_IMAGES_ROOT, photo.folder, name);
      let info;
      try {
        info = await sharp(output).metadata();
      } catch {
        throw new Error("Missing or unreadable generated image: " + output + ". Run npm run build:images.");
      }
      if (info.format !== "webp" || info.width !== Math.min(width, variant.width) || !info.height) {
        throw new Error("Invalid generated image: " + output + ". Run npm run build:images.");
      }
      variants.push({ src: "generated/images/" + photo.folder + "/" + name, width: info.width });
    }
    (catalog[photo.folder] ??= []).push({ index: photo.index, src: "Images/" + photo.folder + "/" + photo.name, width, height, variants });
  }
  const output = "// Generated by npm run build:images or npm run build:manifest.\nconst imageCatalog = " + JSON.stringify(catalog) + ";\n";
  const target = path.join(REPO_ROOT, "image-manifest.js");
  await fs.writeFile(target + ".tmp", output);
  await fs.rename(target + ".tmp", target);
  console.log("Indexed " + photos.length + " photos in " + Object.keys(catalog).length + " folders.");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generateImageManifest();
}
